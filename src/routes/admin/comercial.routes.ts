import { Router } from 'express';
import * as controller from '../../controllers/comercial-admin.controller.js';
import * as schemas from '../../validations/comercial-admin.validation.js';
import { requireRole } from '../../middlewares/auth.middleware.js';
import { validate } from '../../middlewares/validate.middleware.js';
const router = Router();
router.use(requireRole('ADMIN'));
const base = '/productos/:idProducto';
router.get(`${base}/configuracion-comercial`, controller.obtener);
router.post(`${base}/presentaciones`, validate(schemas.crearPresentacionSchema), controller.crearPresentacion);
router.patch(`${base}/presentaciones/:idPresentacion`, validate(schemas.editarPresentacionSchema), controller.editarPresentacion);
router.post(`${base}/perfiles-precio`, validate(schemas.crearPerfilSchema), controller.crearPerfil);
router.patch(`${base}/perfiles-precio/:idPerfilPrecio`, validate(schemas.editarPerfilSchema), controller.editarPerfil);
router.patch(`${base}/variantes/perfiles`, validate(schemas.asignarPerfilesSchema), controller.asignarPerfiles);
router.patch(`${base}/variantes/:idVariante/perfil`, validate(schemas.asignarPerfilSchema), controller.asignarPerfil);
router.post(`${base}/listas-precio/:idListaPrecio/reglas`, validate(schemas.crearReglaSchema), controller.crearRegla);
router.patch(`${base}/listas-precio/:idListaPrecio/reglas/:idReglaPrecio`, validate(schemas.editarReglaSchema), controller.editarRegla);
router.delete(`${base}/listas-precio/:idListaPrecio/reglas/:idReglaPrecio`, controller.eliminarRegla);
export default router;
